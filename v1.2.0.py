def analyse_system(name, m1, m2, snr, fdfplus_over_fmax=10.0, verbose=True):
    """Single-mechanism thresholds and the joint accretion + friction fit.
    The two density amplitudes rho_A (accretion) and rho_B (friction) are
    free and independent here, which asks only whether the SHAPES differ."""
    b = Binary(m1, m2)
    fmin, fmax = b.lisa_band()
    fgrid = make_fgrid(fmin, fmax)

    # fiducial self-interaction: place the friction window around the band
    f_plus = fdfplus_over_fmax * fmax
    y = b.y_for_fdf_plus(f_plus)
    f_minus = b.f_df_minus(y)
    facc1, facc2 = b.f_acc(1, y), b.f_acc(2, y)

    # holes in the high-f accretion regime across the whole band
    acc_include = tuple(i for i, fa in ((1, facc1), (2, facc2)) if fa < fmin)
    regime_ok = dict(df_window=(f_minus < fmin and f_plus > fmax),
                     acc_high_1=(facc1 < fmin), acc_high_2=(facc2 < fmin),
                     df_active=(b.nu < 0.16 or m1 / m2 > 2.6))

    # templates dPsi/drho at rho = 1 g/cm^3 (the signal is linear in rho)
    tA = psi_acc_high(fgrid, b, 1.0, include=acc_include if acc_include else (2,))
    tB = psi_df(fgrid, b, 1.0, f_plus)
    tH = psi_halo(fgrid, b, 1.0)
    tL = psi_acc_low(fgrid, b, 1.0)

    base = list(binary_param_derivs(b, fgrid))

    # (a) single-mechanism detection thresholds
    single = {}
    for lab, t in (('acc', tA), ('df', tB), ('halo', tH), ('acc_low', tL)):
        _, sig, _, _ = invert_fisher(fisher(base + [t], fgrid, snr))
        single[lab] = sig[4]

    # (b) joint accretion + dynamical friction: the attribution question
    Sigma6, sig6, corr6, cond6 = invert_fisher(fisher(base + [tA, tB], fgrid, snr))
    rAB = corr6[4, 5]

    # (c) same, without marginalising over the binary parameters
    _, _, corr2, _ = invert_fisher(fisher([tA, tB], fgrid, snr))

    # (d) all four mechanism shapes together (marginalised)
    labels4 = ['halo(-3PN)', 'acc_low(-4PN)', 'acc_high(-5.5PN)', 'df(-5.5PN+log)']
    try:
        _, _, corrM, _ = invert_fisher(fisher(base + [tH, tL, tA, tB], fgrid, snr))
        mech_corr = corrM[4:, 4:]
    except np.linalg.LinAlgError:
        mech_corr = None

    res = dict(name=name, m1=m1, m2=m2, snr=snr, fmin=fmin, fmax=fmax,
               y=y, cs_over_c=1.0 / np.sqrt(y), f_plus=f_plus, f_minus=f_minus,
               facc1=facc1, facc2=facc2, acc_include=acc_include,
               regime_ok=regime_ok, sigma_single=single,
               sigma_joint_A=sig6[4], sigma_joint_B=sig6[5],
               rAB=rAB, rAB_nomarg=corr2[0, 1],
               degr_A=sig6[4] / single['acc'], degr_B=sig6[5] / single['df'],
               cond6=cond6, mech_corr=mech_corr, mech_labels=labels4,
               binary=b, fgrid=fgrid, templates=dict(A=tA, B=tB, H=tH, L=tL),
               Sigma6=Sigma6)
    if verbose:
        print_report(res)
    return res


