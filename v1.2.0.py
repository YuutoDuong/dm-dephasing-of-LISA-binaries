C_DET, C_VALID, C_TEST = "#1baf7a", "#2a78d6", "#eb6834"   # checked for CVD
INK, MUTED = "#0b0b0b", "#52514e"


def _tex(x):
    m, e = f"{x:.0e}".split("e")
    return rf"${m}\times10^{{{int(e)}}}$"


def make_figure6():
    plt = _setup_matplotlib()

    rows = [("IMRI, $q=10^3$\n$\\varrho=64$", 1e4, 10., 64.),
            ("EMRI, $q=10^4$\n$\\varrho=22$", 1e5, 10., 22.),
            ("$q=15$, $m_1=10^5\\,M_\\odot$\n$\\varrho=30$", 1e5, 1e5 / 15, 30.)]
    bench = []
    for name, m1, m2, snr in rows:
        r = analyse_physical(name, m1, m2, snr, verbose=False)
        bench.append((name, r["rho0_detect"], rho_valid(m1, m2), r["rho0_test"]))

    qs, ratio, ok = [], [], []
    for q in np.concatenate([np.arange(9, 40, 1.0), np.logspace(np.log10(40), 5, 16)]):
        m2 = 1e5 / q
        r = analyse_physical("q", 1e5, m2, 30., verbose=False)
        qs.append(q)
        ratio.append(r["rho0_test"] / rho_valid(1e5, m2))
        ok.append(r["window_covers_band"])
    qs, ratio, ok = map(np.array, (qs, ratio, ok))
    q_edge = qs[ok].min()

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12.5, 5.2),
                                   gridspec_kw={"width_ratios": [1.15, 1]})

    # (a) density ladder
    for k, (name, det, val, tst) in enumerate(bench):
        yk = 2 - k
        ax1.plot([det, val], [yk, yk], color=C_VALID, lw=6, alpha=0.25,
                 solid_capstyle="butt")
        if tst > val:
            ax1.plot([val, tst], [yk, yk], color=MUTED, lw=1.5, ls=(0, (3, 3)))
        ax1.plot(det, yk, "o", ms=9, color=C_DET, mec="white", mew=1.5, zorder=3)
        ax1.plot(val, yk, "s", ms=9, color=C_VALID, mec="white", mew=1.5, zorder=3)
        ax1.plot(tst, yk, "D", ms=7.5, color=C_TEST, mec="white", mew=1.5, zorder=4)
        close = tst < val * 10
        ax1.annotate(f"detect\n{_tex(det)}", (det, yk), xytext=(0, -14),
                     textcoords="offset points", ha="center", va="top",
                     fontsize=8.5, color=INK)
        ax1.annotate(f"model breaks\n{_tex(val)}", (val, yk),
                     xytext=(0, 14 if close else -14), textcoords="offset points",
                     ha="center", va="bottom" if close else "top",
                     fontsize=8.5, color=INK)
        ax1.annotate(f"friction seen\n{_tex(tst)}", (tst, yk),
                     xytext=(14, -14) if close else (0, -14),
                     textcoords="offset points", ha="left" if close else "center",
                     va="top", fontsize=8.5, color=INK)
        if tst > val:
            ax1.annotate(f"friction needs {_tex(tst / val)} more\nthan the model allows",
                         (np.sqrt(val * tst), yk), xytext=(0, 8),
                         textcoords="offset points", ha="center", va="bottom",
                         fontsize=8.5, color=MUTED)
        else:
            ax1.annotate("friction measurable\ninside model validity", (val, yk),
                         xytext=(30, 0), textcoords="offset points", ha="left",
                         va="center", fontsize=8.5, color=MUTED)
    ax1.set_xscale("log")
    ax1.set_xlim(1e-24, 1e-1)
    ax1.set_ylim(-0.75, 2.55)
    ax1.set_yticks([2, 1, 0])
    ax1.set_yticklabels([row[0] for row in bench], fontsize=9.5)
    ax1.grid(axis="y", visible=False)
    ax1.set_xlabel(r"bulk density $\rho_0$  [g cm$^{-3}$]")
    ax1.set_title("(a) Detection, model validity and friction", fontsize=11)

    # (b) one curve, one axis
