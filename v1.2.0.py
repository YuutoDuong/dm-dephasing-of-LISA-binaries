class Binary:
    """Masses in solar masses on input, SI inside. Convention m1 >= m2."""

    def __init__(self, m1_Msun, m2_Msun):
        if m2_Msun > m1_Msun:
            m1_Msun, m2_Msun = m2_Msun, m1_Msun
        self.m1 = m1_Msun * Msun
        self.m2 = m2_Msun * Msun
        self.m = self.m1 + self.m2
        self.mu = self.m1 * self.m2 / self.m
        self.nu = self.mu / self.m
        self.Mc = self.nu ** 0.6 * self.m

    # characteristic frequencies
    def f_isco(self):
        return c ** 3 / (6.0 ** 1.5 * np.pi * G * self.m)

    def f_gamma(self):
        """Cut where v^2 = 0.137 c^2 (Boudon Sec. IV.B.5)."""
        return 0.137 ** 1.5 * c ** 3 / (np.pi * G * self.m)

    def f_obs(self, Tobs=4.0 * YR):
        """GW frequency a time Tobs before merger (Boudon Sec. VI.A)."""
        return 4.149e-5 * (self.Mc / (1e6 * Msun)) ** (-5.0 / 8.0) \
            * (Tobs / YR) ** (-3.0 / 8.0)

    def lisa_band(self):
        """Boudon Table I: fmin = max(2e-5, f_obs), fmax = min(1, f_gamma)."""
        return max(2.0e-5, self.f_obs()), min(1.0, self.f_gamma())

    # regime thresholds, Eqs. 5.5-5.8 solved for f
    def f_acc(self, i, y):
        """Accretion threshold for hole i (1 or 2): supersonic above it."""
        mi = self.m1 if i == 1 else self.m2
        return c ** 3 * mi ** 3 \
            / (3.0 * np.pi * FSTAR * G * self.m * self.mu ** 3 * y)

    def f_df_minus(self, y):
        """Lower dynamical-friction threshold for the lighter hole."""
        return c ** 3 * self.m2 ** 3 \
            / (np.pi * G * self.m * self.mu ** 3 * y ** 1.5)

    def _log_fdf_plus_y1(self):
        """log of f_df^+ at y = 1. Done in log space because mu^15
        overflows float64 for supermassive systems."""
        return (3.0 + 3.0 * np.log(c) + 5.0 * np.log(self.m)
                + 15.0 * np.log(self.mu) - np.log(5832.0 * np.pi * G)
                - 21.0 * np.log(self.m2))

    def f_df_plus(self, y):
        """Upper dynamical-friction threshold for the lighter hole."""
        return np.exp(self._log_fdf_plus_y1() - 1.5 * np.log(y))

    def y_for_fdf_plus(self, f_plus):
        """Invert f_df_plus(y) = f_plus for the density ratio y = rho_a/rho0."""
        return np.exp((2.0 / 3.0) * (self._log_fdf_plus_y1() - np.log(f_plus)))


# ----------------------------------------------------------------------
# 3. Phase model (Psi in radians, x = pi G Mc f / c^3)
# ----------------------------------------------------------------------
def x_of_f(f, b):
    return np.pi * G * b.Mc * f / c ** 3


def psi_vacuum(f, b):
    """Eq. 4.16: leading + 1PN SPA phase."""
    x = x_of_f(f, b)
    onePN = (20.0 / 9.0) * (743.0 / 336.0 + 2.75 * b.nu) \
        * (np.pi * G * b.m * f / c ** 3) ** (2.0 / 3.0)
    return (3.0 / 128.0) * x ** (-5.0 / 3.0) * (1.0 + onePN)


def _dm_prefac(b, rho0_gcm3):
    """Common factor rho0 G^3 Mc^2 / c^6 (dimensionless)."""
    return rho0_gcm3 * GCM3 * G ** 3 * b.Mc ** 2 / c ** 6


def psi_halo(f, b, rho0_gcm3):
    """Eq. 4.18: cloud self-gravity, -3PN, x^(-11/3)."""
    return (25.0 * np.pi / 924.0) * _dm_prefac(b, rho0_gcm3) \
        * x_of_f(f, b) ** (-11.0 / 3.0)


def _acc_mass_factor(b, include=(1, 2)):
    """Sum over included holes of (m_i^3 / mu^2 m)(3 + 2 m_i^2 / (m mu))."""
    tot = 0.0
    for i in include:
        mi = b.m1 if i == 1 else b.m2
        tot += mi ** 3 / (b.mu ** 2 * b.m) * (3.0 + 2.0 * mi ** 2 / (b.m * b.mu))
    return tot


def psi_acc_high(f, b, rho0_gcm3, include=(1, 2)):
    """Eq. 4.19, high-f branch (f > f_acc,i): -5.5PN, x^(-16/3), prop. rho0."""
    return -(25.0 * np.pi / 38912.0) * _dm_prefac(b, rho0_gcm3) \
        * _acc_mass_factor(b, include) * x_of_f(f, b) ** (-16.0 / 3.0)


def psi_acc_low(f, b, rhoa_gcm3, include=(1, 2)):
    """Eq. 4.19, low-f branch (f < f_acc,i): -4PN, x^(-13/3), prop. rho_a.
    The bracket is set to 1, its limit for f << f_acc (Eq. 5.10)."""
    mfac = sum((3.0 + 2.0 * (b.m1 if i == 1 else b.m2) ** 2 / (b.m * b.mu))
               for i in include)
    return -(75.0 * np.pi * FSTAR / 26624.0) * b.nu ** 0.4 \
        * _dm_prefac(b, rhoa_gcm3) * mfac * x_of_f(f, b) ** (-13.0 / 3.0)


def psi_acc_full(f, b, rho0_gcm3, y):
    """Eq. 4.19 in full. Each hole uses the high-f branch above its own
    threshold f_acc,i and the low-f branch (density rho_a = y rho0, bracket
    kept) below it. The two branches join continuously at f_acc,i."""
    x = x_of_f(f, b)
    out = np.zeros_like(f, dtype=float)
    for mi, i in ((b.m1, 1), (b.m2, 2)):
        fa = b.f_acc(i, y)
        k = 3.0 + 2.0 * mi ** 2 / (b.m * b.mu)
        hi = f > fa
        out[hi] += -(25.0 * np.pi / 38912.0) * _dm_prefac(b, rho0_gcm3) \
            * mi ** 3 / (b.mu ** 2 * b.m) * k * x[hi] ** (-16.0 / 3.0)
        lo = ~hi
        r = f[lo] / fa
        bracket = 1.0 - r ** (13.0 / 3.0) + (13.0 / 19.0) * r ** (16.0 / 3.0)
        out[lo] += -(75.0 * np.pi * FSTAR / 26624.0) * b.nu ** 0.4 \
            * _dm_prefac(b, y * rho0_gcm3) * k * x[lo] ** (-13.0 / 3.0) * bracket
    return out


def psi_df(f, b, rho0_gcm3, f_plus):
    """Eq. 4.20, main window f_df^- < f < f_df^+ (lighter hole only):
    -5.5PN carrier x^(-16/3) times the Coulomb-log bracket."""
    x = x_of_f(f, b)
    r = f / f_plus
    bracket = 1.0 + (304.0 / 105.0) * np.log(r) \
        - (361.0 / 105.0) * r ** (16.0 / 3.0) \
        + (256.0 / 105.0) * r ** (19.0 / 3.0)
    mass2 = b.m2 ** 3 / (b.mu ** 2 * b.m)
    return (875.0 * np.pi / 11829248.0) * _dm_prefac(b, rho0_gcm3) \
        * mass2 * x ** (-16.0 / 3.0) * bracket


# ----------------------------------------------------------------------
# 4. Fisher machinery (Eq. 5.3: phase only, amplitude decorrelated)
# ----------------------------------------------------------------------
def make_fgrid(fmin, fmax, n=6000):
    return np.logspace(np.log10(fmin), np.log10(fmax), n)


def fisher(derivs, fgrid, snr):
    """Gamma_ij = SNR^2 * int w dPsi_i dPsi_j / int w,  w = f^(-7/3) / Sn."""
    w = fgrid ** (-7.0 / 3.0) / Sn_LISA(fgrid)
    norm = _trapz(w, fgrid)
    n = len(derivs)
    Gam = np.empty((n, n))
    for i in range(n):
        for j in range(i, n):
            Gam[i, j] = Gam[j, i] = \
                snr ** 2 * _trapz(w * derivs[i] * derivs[j], fgrid) / norm
    return Gam


def invert_fisher(Gam):
    """Invert through the unit-diagonal Fisher C = D^-1 Gam D^-1, which keeps
    the condition number manageable. Returns (covariance, sigmas,
    correlation matrix, condition number of C)."""
    d = np.sqrt(np.diag(Gam))
    D = np.outer(d, d)
    C = Gam / D
    cond = np.linalg.cond(C)
    Sigma = np.linalg.inv(C) / D
    sig = np.sqrt(np.diag(Sigma))
    corr = Sigma / np.outer(sig, sig)
    return Sigma, sig, corr, cond


def binary_param_derivs(b, fgrid):
    """d/dt_c and d/dPhi_c analytically; d/dln m1 and d/dln m2 of the
    vacuum phase by central differences."""
    d_tc = 2.0 * np.pi * fgrid
    d_phic = -np.ones_like(fgrid)
    eps = 1e-6
    out = []
    for which in ('m1', 'm2'):
        m1, m2 = b.m1 / Msun, b.m2 / Msun
        bp = Binary(m1 * (1 + eps), m2) if which == 'm1' else Binary(m1, m2 * (1 + eps))
        bm = Binary(m1 * (1 - eps), m2) if which == 'm1' else Binary(m1, m2 * (1 - eps))
        out.append((psi_vacuum(fgrid, bp) - psi_vacuum(fgrid, bm)) / (2 * eps))
    return d_tc, d_phic, out[0], out[1]


