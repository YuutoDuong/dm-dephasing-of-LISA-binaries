def sweep_mass(q=1e4, snr=30.0, n=16):
    """r_AB and thresholds versus primary mass at fixed mass ratio."""
    rows = []
    for m1 in np.logspace(4, 7, n):
        b = Binary(m1, m1 / q)
        fmin, fmax = b.lisa_band()
        if fmax <= fmin * 1.5:
            continue
        r = analyse_system(f"m1={m1:.2e}", m1, m1 / q, snr, verbose=False)
        rows.append((m1, r['rAB'], r['rAB_nomarg'],
                     r['sigma_single']['acc'], r['degr_A'], r['cond6']))
    return np.array(rows)


def sweep_fdfplus(name, m1, m2, snr, n=15):
    """r_AB versus where the friction threshold f_df^+ sits relative to the
    band. This sets how much the Coulomb log varies across the band."""
    rows = []
    for R in np.logspace(0.05, 3.0, n):     # f_df^+/fmax from ~1.1 to 1000
        r = analyse_system(name, m1, m2, snr, fdfplus_over_fmax=R, verbose=False)
        rows.append((R, r['rAB'], r['rAB_nomarg'], r['degr_A']))
    return np.array(rows)


