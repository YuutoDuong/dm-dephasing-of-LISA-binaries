# 7. Sanity checks
# ----------------------------------------------------------------------
def validate():
    print("\n" + "#" * 72 + "\n#  VALIDATION\n" + "#" * 72)

    # (1) noise floor: RCL sky-averaged minimum is about 1e-20 near 5-10 mHz
    fg = np.logspace(-5, 0, 2000)
    s = np.sqrt(Sn_LISA(fg))
    imin = np.argmin(s)
    print(f"  [noise] min sqrt(Sn) = {s[imin]:.3e} Hz^-1/2 "
          f"at f = {fg[imin]:.3e} Hz  (RCL sky-averaged floor ~1.2e-20)")

    # (2) vacuum phase: leading term ~ x^(-5/3), 1PN a small correction
    b = Binary(1e6, 5e5)
    f0 = 1e-3
    lead = 3.0 / 128.0 * x_of_f(f0, b) ** (-5 / 3)
    print(f"  [vacuum] Mc = {b.Mc/Msun:.4g} Msun; Psi_lead = {lead:.4e}, "
          f"Psi_1PN/Psi_lead - 1 = {psi_vacuum(f0, b)/lead - 1:.3e}")

    # (3) ratio checks, Boudon Eqs. 4.21 and 4.23, at f = 1 Hz, rho0 = 1 g/cm^3
    bb = Binary(2.0, 1.0)
    f0 = 1.0
    vac = 3 / 128 * x_of_f(f0, bb) ** (-5 / 3)
    print(f"  [4.21]  Psi_halo/Psi_gw = {psi_halo(f0, bb, 1.0) / vac:.2e}  "
          f"(paper ~2e-8, mass-independent)")
    ratio_acc = abs(psi_acc_high(f0, bb, 1.0, include=(1,))) / vac
    est_423 = 0.1 * 2.0 ** 4 * 2.0 ** (-5.0 / 3.0)
    print(f"  [4.23]  |Psi_acc,>|/Psi_gw = {ratio_acc:.2e}  "
          f"(paper order-of-magnitude estimate {est_423:.2e})")

    # (4) MBBH threshold vs Boudon Table IV (rho0* ~ 8e-13 g/cm^3, SNR 3e4).
    #     Their value is for large y, where BOTH holes accrete supersonically
    #     across the band, so both enter the high-f template.
    bm = Binary(1e6, 5e5)
    flo, fhi = bm.lisa_band()
    fg = make_fgrid(flo, fhi)
    Gam = fisher(list(binary_param_derivs(bm, fg))
                 + [psi_acc_high(fg, bm, 1.0, include=(1, 2))], fg, 3e4)
    _, sg, _, _ = invert_fisher(Gam)
    print(f"  [Table IV] MBBH rho0* (large y, both holes supersonic) = "
          f"{sg[4]:.2e} g/cm^3  (Boudon et al.: ~8e-13)")
    return sg[4]


# ----------------------------------------------------------------------
# 8. Boudon et al. Table IV, all six LISA entries
# ----------------------------------------------------------------------
# Large y: both holes accrete supersonically across the band and the signal
# measures rho0. Small y: the primary is subsonic across the band and the
# signal measures rho_a = y rho0. Inside each regime the threshold does not
# depend on y, so any y deep in the regime gives the same answer.
TABLE4_PUBLISHED = {  # system: (rho0* large y, rho_a* small y), g/cm^3
    "MBBH": (8e-13, 5e-9), "IMRI": (3e-20, 2e-8), "EMRI": (1e-22, 1e-8)}
TABLE4_SYSTEMS = {"MBBH": (1e6, 5e5, 3e4), "IMRI": (1e4, 10.0, 64.0),
                  "EMRI": (1e5, 10.0, 22.0)}


def table4_threshold(m1, m2, snr, y):
    """1-sigma threshold on rho0 for halo + full accretion at density ratio y."""
    b = Binary(m1, m2)
    fmin, fmax = b.lisa_band()
    f = make_fgrid(fmin, fmax)
    T = psi_halo(f, b, 1.0) + psi_acc_full(f, b, 1.0, y)
    _, s, _, _ = invert_fisher(fisher(list(binary_param_derivs(b, f)) + [T], f, snr))
    return s[4]


def compare_table4(verbose=True):
    rows = []
    for name, (m1, m2, snr) in TABLE4_SYSTEMS.items():
        b = Binary(m1, m2)
        fmin, fmax = b.lisa_band()
        y_hi = 1e16                       # both thresholds below fmin
        assert b.f_acc(1, y_hi) < fmin and b.f_acc(2, y_hi) < fmin
        r0 = table4_threshold(m1, m2, snr, y_hi)
        y_lo = 10.0                       # primary threshold above fmax, y >= 1
        assert b.f_acc(1, y_lo) > fmax
        ra = y_lo * table4_threshold(m1, m2, snr, y_lo)
        rows += [(name, "large y", "rho0*", r0, TABLE4_PUBLISHED[name][0]),
                 (name, "small y", "rho_a*", ra, TABLE4_PUBLISHED[name][1])]
    if verbose:
        print("  system  regime   quantity   this work   Boudon+24   ratio")
        for n, reg, q, ours, pub in rows:
            print(f"  {n:6s}  {reg:7s}  {q:7s}   {ours:.2e}   {pub:.0e}    {ours/pub:.2f}")
    return rows


