# ----------------------------------------------------------------------
# 9. Consistency test for dynamical friction
# ----------------------------------------------------------------------
# In the Boudon et al. model every channel is fixed by the same cloud
# (rho0, y) and the masses, so the model predicts the ratio between
# channels. We test that prediction for friction:
#     Psi_DM = rho0 * [ T_rest(f) + lam * T_df(f) ],   model: lam = 1
#     T_rest = halo gravity + full accretion on both holes (Eq. 4.19)
#     T_df   = dynamical friction on the lighter hole (Eq. 4.20)
# rho0_detect : 1-sigma threshold for the full model signal
# rho0_test   : density where sigma(lam) = 1, i.e. friction is measured at
#               its predicted size at 1 sigma. sigma(lam) scales as 1/rho0,
#               so rho0_test equals sigma(lam) evaluated at rho0 = 1.
def analyse_physical(name, m1, m2, snr, fdfplus_over_fmax=10.0, verbose=True):
    b = Binary(m1, m2)
    fmin, fmax = b.lisa_band()
    f = make_fgrid(fmin, fmax)
    f_plus = fdfplus_over_fmax * fmax
    y = b.y_for_fdf_plus(f_plus)

    T_halo = psi_halo(f, b, 1.0)
    T_acc = psi_acc_full(f, b, 1.0, y)
    T_df = psi_df(f, b, 1.0, f_plus)
    T_rest = T_halo + T_acc
    base = list(binary_param_derivs(b, f))

    # (1) detecting the full model signal: one DM parameter, rho0
    _, s5, _, _ = invert_fisher(fisher(base + [T_rest + T_df], f, snr))
    rho0_detect = s5[4]

    # (2) consistency test at rho0 = 1: dPsi/drho0 = T_rest + T_df,
    #     dPsi/dlam = rho0 * T_df
    _, s6, c6, cond = invert_fisher(fisher(base + [T_rest + T_df, T_df], f, snr))
    rho0_test = s6[5]

    res = dict(name=name, m1=m1, m2=m2, snr=snr, y=y, f_acc1=b.f_acc(1, y),
               fmin=fmin, fmax=fmax,
               df_over_rest_fmin=abs(T_df[0] / T_rest[0]),
               df_over_rest_fmax=abs(T_df[-1] / T_rest[-1]),
               halo_over_acc_fmin=abs(T_halo[0] / T_acc[0]),
               rho0_detect=rho0_detect, rho0_test=rho0_test,
               ratio=rho0_test / rho0_detect, r_rho0_lam=c6[4, 5], cond=cond,
               window_covers_band=bool(b.f_df_minus(y) < fmin and b.nu < 0.16))
    if verbose:
        print(f"\n--- {name}  (y = {y:.3e}, f_acc,1 = {res['f_acc1']:.3e} Hz, "
              f"band [{fmin:.2e}, {fmax:.2e}] Hz)")
        print(f"  |T_df / T_rest|     at fmin {res['df_over_rest_fmin']:.2e}, "
              f"at fmax {res['df_over_rest_fmax']:.2e}")
        print(f"  |T_halo / T_acc|    at fmin {res['halo_over_acc_fmin']:.2e}")
        print(f"  rho0 to detect the environment : {rho0_detect:.2e} g/cm^3")
        print(f"  rho0 to see friction (sig_lam=1): {rho0_test:.2e} g/cm^3")
        print(f"  ratio test/detect               : {res['ratio']:.2e}")
        print(f"  corr(rho0, lam) = {res['r_rho0_lam']:+.6f}   cond = {cond:.1e}")
    return res


# ----------------------------------------------------------------------
# 10. Domain of validity of the linearized model
# ----------------------------------------------------------------------
# The model assumes the environment changes the frequency drift by a small
# fraction delta. Since dPsi/df = 2 pi t(f), d^2Psi/df^2 = 2 pi / fdot, so
#     delta(f) = -Psi_env''(f) / Psi_gw''(f).
# delta is linear in rho0, so rho_valid(eps) = eps / max_f |delta(rho0 = 1)|.
def _f2_second_deriv(psi, lnf):
    """f^2 d^2psi/df^2 on a log-spaced grid."""
    d1 = np.gradient(psi, lnf)
    return np.gradient(d1, lnf) - d1


def rho_valid(m1, m2, eps=0.1, fdfplus_over_fmax=10.0, n=20000):
    b = Binary(m1, m2)
    fmin, fmax = b.lisa_band()
    f = np.logspace(np.log10(fmin), np.log10(fmax), n)
    lnf = np.log(f)
    fp = fdfplus_over_fmax * fmax
    y = b.y_for_fdf_plus(fp)
    T = psi_halo(f, b, 1.0) + psi_acc_full(f, b, 1.0, y) + psi_df(f, b, 1.0, fp)
    delta1 = np.abs(_f2_second_deriv(T, lnf) / _f2_second_deriv(psi_vacuum(f, b), lnf))
    return eps / delta1[20:-20].max()     # drop np.gradient edge points


# ----------------------------------------------------------------------
# 11. Mass-ratio window where friction is measurable
# ----------------------------------------------------------------------
# At fixed (m1, SNR, window placement R), scan q and report:
#   the lowest q at which the friction window covers the band,
#   the largest q with rho_test < rho_valid(|delta| = 0.1),
#   the largest q with rho_test < 10 rho_valid (|delta| = 1).
WINDOW_CASES = [(1e5, 30, 10), (1e5, 10, 10), (1e5, 100, 10), (1e5, 30, 3),
                (1e5, 30, 100), (1e4, 30, 10), (1e6, 30, 10)]


def scan_window(m1, snr, R, qgrid=np.arange(6, 61, 1.0)):
    q_win, q01, q1 = None, None, None
    for q in qgrid:
        m2 = m1 / q
        b = Binary(m1, m2)
        fmin, fmax = b.lisa_band()
        if fmax <= 1.5 * fmin:
            continue
        r = analyse_physical("q", m1, m2, snr, fdfplus_over_fmax=R, verbose=False)
        if not r['window_covers_band']:
            continue
        q_win = q if q_win is None else q_win
        v = rho_valid(m1, m2, fdfplus_over_fmax=R, n=8000)
        if r['rho0_test'] < v:
            q01 = q
        if r['rho0_test'] < 10 * v:
            q1 = q
    return q_win, q01, q1


# ----------------------------------------------------------------------
# 12. Exact-likelihood MCMC check (optional)
# ----------------------------------------------------------------------
# For h = A f^(-7/6) exp(i Psi) with fixed amplitude, the noise-free
# log-likelihood is exactly
#     ln L(theta) = -SNR^2 [1 - <cos(Psi(theta) - Psi(theta_0))>_w],
#     <g>_w = int w g df / int w df,   w = f^(-7/3) / Sn(f).
# Expanding cos to second order gives the Fisher matrix back, so any gap
# between the chain and Fisher measures what linearization throws away.
# theta = (t_c, Phi_c, ln m1, ln m2, rho_A, rho_B), injected at
# rho_A = rho_B = 0 as in the Fisher analysis. Flat priors; negative
# densities allowed, as in Fisher. emcee samples in coordinates whitened by
# the Fisher covariance so the near-perfect correlation does not stall it.
def run_mcmc(name, m1, m2, snr, n_grid=4000, nwalkers=MCMC_WALKERS,
             nsteps=MCMC_STEPS, burn=MCMC_BURN, seed=1):
    import emcee

    r = analyse_system(name, m1, m2, snr, verbose=False)
    b0 = Binary(m1, m2)
    fmin, fmax = b0.lisa_band()
    f = make_fgrid(fmin, fmax, n_grid)
    w = f ** (-7.0 / 3.0) / Sn_LISA(f)
    dw = np.zeros_like(f)                 # trapezoid weights, as in fisher()
    dw[1:] += 0.5 * np.diff(f)
    dw[:-1] += 0.5 * np.diff(f)
    W = w * dw / np.sum(w * dw)
    f_plus = r['f_plus']
    inc = r['acc_include'] if r['acc_include'] else (2,)

    def psi(theta):
        tc, phic, lm1, lm2, rA, rB = theta
        b = Binary(np.exp(lm1) / Msun, np.exp(lm2) / Msun)
        return (2 * np.pi * f * tc - phic + psi_vacuum(f, b)
                + psi_acc_high(f, b, rA, include=inc) + psi_df(f, b, rB, f_plus))

    theta0 = np.array([0.0, 0.0, np.log(b0.m1), np.log(b0.m2), 0.0, 0.0])
    psi0 = psi(theta0)

    def lnlike(theta):
        if theta[3] > theta[2]:           # keep the m1 >= m2 labelling
            return -np.inf
        return -snr ** 2 * (1.0 - np.sum(W * np.cos(psi(theta) - psi0)))

    # Fisher on the same grid, for whitening and for the comparison
    base = list(binary_param_derivs(b0, f))
    tA = psi_acc_high(f, b0, 1.0, include=inc)
    tB = psi_df(f, b0, 1.0, f_plus)
    Sigma, sig, corr, _ = invert_fisher(fisher(base + [tA, tB], f, snr))
    lam, V = np.linalg.eigh(corr)         # theta = theta0 + L z, Sigma = L L^T
    L = np.diag(sig) @ V @ np.diag(np.sqrt(np.clip(lam, 0, None)))

    rng = np.random.default_rng(seed)
    p0 = 0.1 * rng.standard_normal((nwalkers, 6))
    # emcee copies NumPy's global random state when the sampler is built,
    # so seed it too; otherwise every run gives slightly different numbers.
    np.random.seed(seed)
    sampler = emcee.EnsembleSampler(nwalkers, 6, lambda z: lnlike(theta0 + L @ z))
    sampler.run_mcmc(p0, nsteps, progress=False)
    z = sampler.get_chain(discard=burn, flat=True)
    th = theta0 + z @ L.T

    sig_mc = th.std(axis=0)
    r_mc = np.corrcoef(th[:, 4], th[:, 5])[0, 1]
    try:
        tau = sampler.get_autocorr_time(discard=burn, quiet=True)
    except Exception:
        tau = np.full(6, np.nan)
    out = dict(name=name, sig_fisher=sig, sig_mcmc=sig_mc,
               r_fisher=corr[4, 5], r_mcmc=r_mc, z_std=z.std(axis=0),
               acc=np.mean(sampler.acceptance_fraction),
               tau_max=np.nanmax(tau), n_eff=len(z) / np.nanmax(tau))
    labels = ["t_c", "Phi_c", "ln m1", "ln m2", "rho_A", "rho_B"]
    print(f"\n=== {name}  (grid {n_grid}, {nwalkers}x{nsteps} steps, burn {burn})")
    print(f"  acceptance {out['acc']:.2f}, max autocorr time {out['tau_max']:.0f}, "
          f"effective samples ~{out['n_eff']:.0f}")
    print("  param    sigma_Fisher   sigma_MCMC   ratio")
    for i, lab in enumerate(labels):
        print(f"  {lab:6s}   {sig[i]:.3e}    {sig_mc[i]:.3e}   {sig_mc[i]/sig[i]:.3f}")
    print(f"  r_AB: Fisher {corr[4, 5]:+.6f}   MCMC {r_mc:+.6f}")
    print(f"  whitened-coordinate std (1 if Fisher exact): {np.round(out['z_std'], 3)}")
    return out


